    public function run(): void
    {
        $this->command->info('Seeding missing Level 2 categories for Excel batch import...');
        $now = now();
        $insertedCount = 0;
        $updatedCount = 0;

        foreach (self::NEW_CATEGORIES as $cat) {
            $catId = $cat['id'];
            $existing = DB::table('new_categories')->where('id', $catId)->first();

            $categoryData = [
                'parent_id' => $cat['parent_id'],
                'level' => $cat['level'],
                'name_ar' => $cat['name_ar'],
                'name_en' => $cat['name_en'],
                'name_de' => $cat['name_de'],
                'name_es' => $cat['name_es'],
                'name_tr' => $cat['name_tr'],
                'name_zh' => $cat['name_zh'],
                'slug' => $cat['slug'],
                'sort_order' => $cat['sort_order'],
                'status' => 'active',
                'icon' => $cat['icon'],
                'disk' => 'public',
                'updated_at' => $now,
            ];

            if ($existing) {
                DB::table('new_categories')->where('id', $catId)->update($categoryData);
                $updatedCount++;
                $this->command->line("  [UPDATED] Category ID {$catId}: '{$cat['name_ar']}'");
            } else {
                $categoryData['id'] = $catId;
                $categoryData['created_at'] = $now;
                DB::table('new_categories')->insert($categoryData);
                $insertedCount++;
                $this->command->line("  [INSERTED] Category ID {$catId}: '{$cat['name_ar']}' ({$cat['name_en']})");
            }

            // SEO Metadata
            DB::table('seo_metadata')->updateOrInsert(
                [
                    'seoable_type' => 'category_v2',
                    'seoable_id' => $catId,
                ],
                [
                    'meta_title' => json_encode([
                        'ar' => $cat['seo_title_ar'],
                        'en' => $cat['seo_title_en'],
                    ], JSON_UNESCAPED_UNICODE),
                    'meta_description' => json_encode([
                        'ar' => $cat['meta_desc_ar'],
                        'en' => $cat['meta_desc_en'],
                    ], JSON_UNESCAPED_UNICODE),
                    'updated_at' => $now,
                    'created_at' => $now,
                ]
            );
        }

        $this->command->info("Completed seeding: {$insertedCount} inserted, {$updatedCount} updated.");
    }
